// Concatenates the CSS files the site <head> loads from jsDelivr into ONE file
// (css/site.css) so the render-blocking chain is a single request.
//   node scripts/build-site-css.mjs
// Re-run after editing any source file below, then commit css/site.css.
import { readFileSync, writeFileSync } from "node:fs";
const SOURCES = [
  "css/components/site-utils.css",
  "css/effects/link-underline.css",
  "css/core/scrollbar.css",
  "css/components/locale-switch.css",
];
const parts = SOURCES.map((f) => `/* ── ${f} ── */\n${readFileSync(f, "utf8").trim()}\n`);
const out = `/*!\n * site.css — generated by scripts/build-site-css.mjs, do not edit by hand.\n * Sources: ${SOURCES.join(", ")}\n */\n\n${parts.join("\n")}`;
writeFileSync("css/site.css", out);
console.log("css/site.css", out.length, "bytes from", SOURCES.length, "files");
